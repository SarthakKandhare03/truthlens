// Where original photos (and their signature proofs) are kept.
//
// The blockchain only stores a pointer (storageURI). The original is needed
// later for two things: re-checking the signature, and drawing the tamper
// heatmap against an edited copy.
//
// Two interchangeable adapters behind one interface:
//   local://originals/<sha>/image.jpg   a folder on this server (development)
//   s3://<bucket>/originals/<sha>/...   AWS S3 or any S3-compatible store
// Select with STORAGE_DRIVER=local|s3. Reading always follows the URI's own
// scheme, so records written before a switch keep working.
//
// Files are named after their SHA-256 (content addressing): a name can never
// point at different bytes, and duplicates are impossible by construction.
//
// Trade-off: on a serverless host (e.g. Vercel) the local disk is temporary,
// so production needs S3. Originals are publicly readable in this demo (like a
// news agency's archive); a private deployment would put /api/images behind auth.
import "server-only";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { config } from "./config";
import { ServiceError } from "./errors";

export interface StorageAdapter {
  readonly scheme: "local" | "s3";
  /** Stores bytes under `key` and returns the URI to put on-chain. */
  put(key: string, bytes: Uint8Array, contentType: string): Promise<string>;
  /** Bytes for a URI this adapter produced, or null if it does not exist. */
  get(uri: string): Promise<Uint8Array | null>;
}

// Keys are generated by us from validated hashes, but we still refuse anything
// that could escape the storage root ("../") or contain odd characters.
const SAFE_KEY = /^[a-z0-9][a-z0-9/_.-]*$/;
function assertSafeKey(key: string) {
  if (!SAFE_KEY.test(key) || key.includes("..")) throw new Error(`Unsafe storage key: ${key}`);
}

/** Storage layout for one registered image. */
export function storageKeys(sha256: string, extension: string) {
  const id = sha256.replace(/^0x/, "").toLowerCase();
  return { image: `originals/${id}/image.${extension}`, proof: `originals/${id}/proof.json` };
}

/** The proof file sits next to the image: same folder, fixed name. */
export function proofUriFor(imageUri: string): string {
  return imageUri.replace(/\/image\.[a-z0-9]+$/, "/proof.json");
}

// ---------------------------------------------------------------------------
// Local folder
// ---------------------------------------------------------------------------

export class LocalStorage implements StorageAdapter {
  readonly scheme = "local" as const;
  constructor(private readonly root: string) {}

  private resolve(key: string): string {
    assertSafeKey(key);
    const full = path.resolve(this.root, key);
    if (!full.startsWith(path.resolve(this.root) + path.sep)) throw new Error("Path escapes storage root");
    return full;
  }

  // The interface's contentType argument is not needed here: a local file does
  // not store it (the MIME type is kept in proof.json instead).
  async put(key: string, bytes: Uint8Array): Promise<string> {
    const file = this.resolve(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, bytes);
    return `local://${key}`;
  }

  async get(uri: string): Promise<Uint8Array | null> {
    if (!uri.startsWith("local://")) throw new Error(`Not a local URI: ${uri}`);
    try {
      return new Uint8Array(await readFile(this.resolve(uri.slice("local://".length))));
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw err;
    }
  }
}

// ---------------------------------------------------------------------------
// AWS S3 (or S3-compatible). The SDK is loaded only when actually used.
// ---------------------------------------------------------------------------

export class S3Storage implements StorageAdapter {
  readonly scheme = "s3" as const;
  private client: Promise<import("@aws-sdk/client-s3").S3Client> | null = null;

  constructor(
    private readonly bucket: string,
    private readonly region: string,
    private readonly endpoint?: string,
  ) {}

  private sdk() {
    return import("@aws-sdk/client-s3");
  }

  private getClient() {
    // Credentials come from the standard AWS environment variables
    // (AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY) or an attached IAM role.
    this.client ??= this.sdk().then(
      ({ S3Client }) =>
        new S3Client({ region: this.region, endpoint: this.endpoint, forcePathStyle: Boolean(this.endpoint) }),
    );
    return this.client;
  }

  async put(key: string, bytes: Uint8Array, contentType: string): Promise<string> {
    assertSafeKey(key);
    const { PutObjectCommand } = await this.sdk();
    await (await this.getClient()).send(
      new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: bytes, ContentType: contentType }),
    );
    return `s3://${this.bucket}/${key}`;
  }

  async get(uri: string): Promise<Uint8Array | null> {
    const match = /^s3:\/\/([^/]+)\/(.+)$/.exec(uri);
    if (!match) throw new Error(`Not an S3 URI: ${uri}`);
    const [, bucket, key] = match;
    assertSafeKey(key);
    const { GetObjectCommand } = await this.sdk();
    try {
      const res = await (await this.getClient()).send(new GetObjectCommand({ Bucket: bucket, Key: key }));
      return res.Body ? new Uint8Array(await res.Body.transformToByteArray()) : null;
    } catch (err) {
      if ((err as { name?: string }).name === "NoSuchKey") return null;
      throw err;
    }
  }
}

// ---------------------------------------------------------------------------
// Factory
// ---------------------------------------------------------------------------

let local: LocalStorage | null = null;
let s3: S3Storage | null = null;

function localAdapter() {
  return (local ??= new LocalStorage(config.storageLocalDir));
}
function s3Adapter() {
  const { bucket, region, endpoint } = config.s3;
  if (!bucket) throw new ServiceError(503, "STORAGE_NOT_CONFIGURED", "STORAGE_DRIVER=s3 but S3_BUCKET is not set");
  return (s3 ??= new S3Storage(bucket, region, endpoint));
}

/** Adapter used for NEW uploads (STORAGE_DRIVER). */
export function writeStorage(): StorageAdapter {
  return config.storageDriver === "s3" ? s3Adapter() : localAdapter();
}

/** Reads any URI with the adapter matching its scheme. */
export function readFromStorage(uri: string): Promise<Uint8Array | null> {
  if (uri.startsWith("local://")) return localAdapter().get(uri);
  if (uri.startsWith("s3://")) return s3Adapter().get(uri);
  return Promise.resolve(null);
}
